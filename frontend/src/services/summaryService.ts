import type { AISummaryInput, AISummaryOutput, DailyRecord, SupportedLanguage } from '../types';

// ── Rule-based summary logic ────────────────────────────────────────────────

function avg(arr: number[]): number {
  if (!arr.length) return 0;
  return arr.reduce((s, v) => s + v, 0) / arr.length;
}

function trend(current: number, previous: number): 'increased' | 'decreased' | 'stable' {
  const pct = ((current - previous) / (previous || 1)) * 100;
  if (pct > 3) return 'increased';
  if (pct < -3) return 'decreased';
  return 'stable';
}

function buildEnglishSummary(records: DailyRecord[]): string {
  if (!records.length) {
    return 'No data is available for the selected period. Please select a different date range or patient.';
  }

  const half = Math.floor(records.length / 2);
  const first = records.slice(0, half || 1);
  const second = records.slice(half);

  const firstSteps = avg(first.map((r) => r.steps));
  const secondSteps = avg(second.map((r) => r.steps));
  const stepsTrend = trend(secondSteps, firstSteps);

  const firstSpeed = avg(first.map((r) => r.gait_speed));
  const secondSpeed = avg(second.map((r) => r.gait_speed));
  const speedTrend = trend(secondSpeed, firstSpeed);

  const firstStride = avg(first.map((r) => r.stride_length_cm));
  const secondStride = avg(second.map((r) => r.stride_length_cm));
  const strideTrend = trend(secondStride, firstStride);

  const firstAsym = avg(first.map((r) => r.gait_asymmetry));
  const secondAsym = avg(second.map((r) => r.gait_asymmetry));
  const asymTrend = trend(secondAsym, firstAsym);

  const firstEnergy = avg(first.map((r) => r.energy_harvested_mj));
  const secondEnergy = avg(second.map((r) => r.energy_harvested_mj));
  const energyTrend = trend(secondEnergy, firstEnergy);

  const firstSleep = avg(first.map((r) => r.sleep_score));
  const secondSleep = avg(second.map((r) => r.sleep_score));
  const sleepTrend = trend(secondSleep, firstSleep);

  const firstCondition = avg(first.map((r) => r.general_condition_score));
  const secondCondition = avg(second.map((r) => r.general_condition_score));
  const conditionTrend = trend(secondCondition, firstCondition);

  const firstPain = avg(first.map((r) => r.pain_score));
  const secondPain = avg(second.map((r) => r.pain_score));
  const painTrend = trend(secondPain, firstPain);

  const avgCompleteness = avg(records.map((r) => r.data_completeness));
  const period = records.length === 1 ? 'the selected day' : `the ${records.length}-day monitoring period`;

  const lines: string[] = [
    `[DEMO DATA — NOT FOR CLINICAL USE]\n`,
    `During ${period}, the system recorded the following trends for the selected patient:\n`,
    `• Walking Activity: Step count has ${stepsTrend} over the observed period. ` +
      `The system observed an average of approximately ${Math.round(secondSteps).toLocaleString()} steps ` +
      `in the latter half of the monitoring window.\n`,
    `• Gait Speed: The measured gait speed has ${speedTrend}. ` +
      `The recorded average speed during the latter period was approximately ${secondSpeed.toFixed(2)} m/s.\n`,
    `• Stride Length: The measured stride length has ${strideTrend} ` +
      `(latter-period average ≈ ${secondStride.toFixed(1)} cm).\n`,
    `• Gait Asymmetry: The measured gait asymmetry has ${asymTrend} ` +
      `(latter-period average ≈ ${secondAsym.toFixed(1)}%).\n`,
    `• Energy Harvesting: The system observed that harvested energy has ${energyTrend} ` +
      `(latter-period average ≈ ${secondEnergy.toFixed(2)} mJ), which is correlated with recorded activity levels.\n`,
    `• Patient-Reported Sleep: Self-reported sleep score has ${sleepTrend} ` +
      `(latter-period average ≈ ${secondSleep.toFixed(0)}/100).\n`,
    `• Self-Reported General Condition: The recorded general-condition score has ${conditionTrend} ` +
      `(latter-period average ≈ ${secondCondition.toFixed(0)}/100).\n`,
    `• Self-Reported Pain: The recorded pain score has ${painTrend} ` +
      `(latter-period average ≈ ${secondPain.toFixed(0)}/100).\n`,
    `• Data Completeness: Average data completeness was ${avgCompleteness.toFixed(1)}% for the period.\n`,
    `\nNote: This summary is generated by a prototype rule-based system using demonstration data. ` +
      `It does not constitute a medical diagnosis or clinical assessment. ` +
      `All values are demonstration data only.`,
  ];

  return lines.join('');
}

