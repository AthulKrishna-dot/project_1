/**
 * Generate a clinical-style rehabilitation summary.
 *
 * @param input - Patient data and language selection.
 * @returns Deterministic rule-based summary (demo mode).
 *
 * FUTURE INTEGRATION:
 *   Replace this function body with:
 *     const response = await fetch('http://localhost:11434/api/generate', {
 *       method: 'POST',
 *       body: JSON.stringify({ model: 'gemma2:2b', prompt: buildPrompt(input) }),
 *     });
 */
export async function generateClinicalSummary(input: AISummaryInput): Promise<AISummaryOutput> {
  // Simulate slight processing delay (realistic UX)
  await new Promise((resolve) => setTimeout(resolve, 800));

  const englishBody = buildEnglishSummary(input.records);
  const header = TRANSLATION_HEADERS[input.language] ?? '';
  const summary = header + englishBody;

  return {
    summary,
    language: input.language,
    generated_at: new Date().toISOString(),
    model_used: 'Rule-Based Demo (Local SLM — Planned)',
    is_demo: true,
  };
}

