// pages/AISummary.tsx
import React, { useEffect, useState } from 'react';
import { Brain, Download, RefreshCw, AlertTriangle, Info, Cpu } from 'lucide-react';
import type { PatientId, SupportedLanguage, AISummaryOutput, DailyRecord } from '../types';
import { getPatientData } from '../services/dataService';
import { generateClinicalSummary, LANGUAGE_LABELS } from '../services/summaryService';
import { exportSummaryText } from '../utils/csvExport';
import PageHeader from '../components/common/PageHeader';
import Card from '../components/common/Card';

interface Props { selectedPatient: PatientId; selectedDate: string; }

const LANGUAGES: SupportedLanguage[] = ['en', 'ta', 'ml', 'hi'];

