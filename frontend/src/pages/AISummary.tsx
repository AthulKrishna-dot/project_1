export default function AISummary({ selectedPatient }: Props) {
  const [records, setRecords] = useState<DailyRecord[]>([]);
  const [language, setLanguage] = useState<SupportedLanguage>('en');
  const [result, setResult] = useState<AISummaryOutput | null>(null);
  const [generating, setGenerating] = useState(false);
  const [loading, setLoading] = useState(true);
  const [from, setFrom] = useState('2026-07-01');
  const [to, setTo] = useState('2026-07-31');

  useEffect(() => {
    setLoading(true);
    getPatientData(selectedPatient).then(setRecords).finally(() => setLoading(false));
    setResult(null);
  }, [selectedPatient]);

  const filteredRecords = records.filter((r) => r.date >= from && r.date <= to);

  async function handleGenerate() {
    setGenerating(true);
    try {
      const output = await generateClinicalSummary({
        patient_id: selectedPatient,
        date_range: { from, to },
        records: filteredRecords,
        language,
      });
      setResult(output);
    } finally {
      setGenerating(false);
    }
  }

  return (
    <div className="space-y-6">
      <PageHeader
        title="AI Rehabilitation Summary"
        subtitle="Rule-based clinical summary generator — Demo Mode"
        icon={<Brain size={20} />}
      />

      {/* Important disclaimer */}
      <div className="flex items-start gap-2 px-4 py-3 bg-red-50 border border-red-200 rounded-xl text-red-800">
        <AlertTriangle size={14} className="shrink-0 mt-0.5 text-red-500" />
        <p className="text-xs leading-snug">
          <strong>Important:</strong> This summary is generated by a prototype rule-based system using demonstration data.
          It does <strong>NOT</strong> constitute a medical diagnosis, clinical assessment, or treatment recommendation.
          All data is fictional. Not for clinical use.
        </p>
      </div>

      {/* SLM Integration notice */}
      <div className="flex items-start gap-2 px-4 py-3 bg-blue-50 border border-blue-200 rounded-xl text-blue-700">
        <Cpu size={14} className="shrink-0 mt-0.5 text-blue-500" />
        <p className="text-xs leading-snug">
          <strong>Local AI / SLM Integration: Planned (Phase 6).</strong> The current system uses a deterministic
          rule-based generator. A quantized local language model (e.g., Gemma-2B, Phi-3-mini) will be integrated
          in Phase 6 via Ollama or a local FastAPI endpoint. No cloud AI APIs are used or required.
        </p>
      </div>

      {/* Data flow diagram */}
      <Card title="Multimodal Data Pipeline" subtitle="Architecture overview — planned integration">
        <DataFlowDiagram />
      </Card>

      {/* Controls */}
      <Card title="Generate Summary" subtitle="Select parameters and generate a summary">
        <div className="flex flex-wrap items-end gap-4">
          <div>
            <label className="block text-xs font-medium text-slate-600 mb-1">From Date</label>
            <input type="date" value={from} onChange={(e) => setFrom(e.target.value)}
              className="text-sm border border-slate-200 rounded-lg px-3 py-2 focus:outline-none focus:ring-2 focus:ring-teal-500" />
          </div>
          <div>
            <label className="block text-xs font-medium text-slate-600 mb-1">To Date</label>
            <input type="date" value={to} onChange={(e) => setTo(e.target.value)}
              className="text-sm border border-slate-200 rounded-lg px-3 py-2 focus:outline-none focus:ring-2 focus:ring-teal-500" />
          </div>
          <div>
            <label className="block text-xs font-medium text-slate-600 mb-1">Language</label>
            <select value={language} onChange={(e) => setLanguage(e.target.value as SupportedLanguage)}
              className="text-sm border border-slate-200 rounded-lg px-3 py-2 focus:outline-none focus:ring-2 focus:ring-teal-500 bg-white">
              {LANGUAGES.map((l) => (
                <option key={l} value={l}>{LANGUAGE_LABELS[l]}</option>
              ))}
            </select>
          </div>
          <button
            onClick={handleGenerate}
            disabled={generating || loading}
            className="flex items-center gap-2 px-4 py-2 bg-teal-600 text-white text-sm font-medium rounded-lg hover:bg-teal-700 disabled:opacity-50 disabled:cursor-not-allowed transition-colors"
          >
            {generating ? (
              <><RefreshCw size={14} className="animate-spin" /> Generating...</>
            ) : (
              <><Brain size={14} /> Generate Summary</>
            )}
          </button>
          <p className="text-xs text-slate-400">{filteredRecords.length} records in range</p>
        </div>
      </Card>

      {/* Summary output */}
      {result && (
        <Card
          title="Clinical Summary"
          subtitle={`Generated at ${new Date(result.generated_at).toLocaleString()} — ${LANGUAGE_LABELS[result.language]}`}
          actions={
            <button
              onClick={() => exportSummaryText(result.summary, selectedPatient, LANGUAGE_LABELS[result.language])}
              className="flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium bg-slate-100 text-slate-700 rounded-lg hover:bg-slate-200"
            >
              <Download size={12} /> Download
            </button>
          }
        >
          {/* Model info */}
          <div className="flex items-center gap-2 mb-3 px-3 py-2 bg-slate-50 rounded-lg border border-slate-100">
            <Cpu size={13} className="text-slate-400" />
            <span className="text-xs text-slate-500">Model: {result.model_used}</span>
            {result.is_demo && (
              <span className="ml-auto px-1.5 py-0.5 text-[9px] font-bold bg-amber-100 text-amber-700 rounded uppercase">Demo</span>
            )}
          </div>
          {/* Summary text */}
          <pre className="text-xs text-slate-700 leading-relaxed whitespace-pre-wrap font-sans bg-slate-50 rounded-lg p-4 border border-slate-100 max-h-96 overflow-y-auto">
            {result.summary}
          </pre>
        </Card>
      )}
    </div>
  );
}
